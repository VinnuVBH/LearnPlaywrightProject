// COncept of Template literals

let firstName = 'Vinutha';
let fullName = `Hi ${firstName} BH`;
console.log(fullName);

const name = 'World';
console.log(`Hello ${name}`);  // template literal: Hello World
console.log('Hello ${name}');  // single quote: here ${name} will not be imported
console.log("Hello ${name}");  // double quote: here ${name} will not be imported