let a = true;
let b = false;

console.log(a && b); // Logical AND operator - returns true if both operands are true, otherwise returns false
console.log(a || b); // Logical OR operator - returns true if at least one of the operands is true, otherwise returns false
console.log(!a); // Logical NOT operator - returns true if the operand is false, and false if the operand is true