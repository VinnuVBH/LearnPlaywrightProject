// Preincrement operator

let a = 10;
console.log(a);
let b = ++a;  // ++a means first increment of a happens and the the incremented value is assigned to b
console.log(b);
console.log(a);

// Postincrement operator

let c = 10;
console.log(c);
let d = c++; // c++ means firt c value is assigned to d and the the value of c is increased by 1
console.log(d);
console.log(c);