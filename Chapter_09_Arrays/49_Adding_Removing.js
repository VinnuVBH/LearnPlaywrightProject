let arr = [2, 4];
console.log(arr);
// adding elements in the end
arr.push(5);
console.log(arr);
arr.push(3, 67, 78);
console.log(arr);

// removing elements from the end

arr.pop();
console.log(arr);

// add in the begining

arr.unshift(0);
console.log(arr);

// remove in the begining

arr.shift();
console.log(arr);
